// Writes src/plugins/targets.ts: the name of every component a plugin can reach, so a plugin that
// names one that no longer exists fails its typecheck. `--check` only says whether it is current.
import { readFileSync, writeFileSync } from 'node:fs'
import { scanTargets } from '../plugin-targets'

const file = new URL('../src/plugins/targets.ts', import.meta.url)
const names = [...scanTargets().keys()].sort()
const code = `// Generated by \`bun run plugin-targets\`: every component of the app a plugin can reach by name.
export type Target =
${names.map((n) => `  | '${n}'`).join('\n')}
`
if (process.argv.includes('--check')) {
  if (readFileSync(file, 'utf8') !== code) {
    console.error(
      'src/plugins/targets.ts is out of date: run `bun run --cwd apps/web plugin-targets`',
    )
    process.exit(1)
  }
} else writeFileSync(file, code)
